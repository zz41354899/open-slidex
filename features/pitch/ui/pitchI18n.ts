const PitchLocaleOverrideContext = createContext<Locale | null>(null);

export function PitchLocaleOverride({ children, locale }: { children: ReactNode; locale?: Locale }) {
  return createElement(PitchLocaleOverrideContext.Provider, { value: locale ?? null }, children);
}

export function pitchHasTranslation(text: string): text is PitchTranslationKey {
  return Object.prototype.hasOwnProperty.call(zhTw, text);
}

export function pitchTranslate(locale: Locale, text: string, params?: PitchTranslationParams) {
  const translated = pitchHasTranslation(text) ? pitchDictionaries[locale][text] : text;
  if (!params) return translated;

  return translated.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (placeholder, name: string) => {
    const value = params[name];
    return value === undefined ? placeholder : String(value);
  });
}

export function usePitchI18n() {
  const workspaceLocale = useOptionalI18n()?.locale ?? defaultLocale;
  const localeOverride = useContext(PitchLocaleOverrideContext);
  const locale = localeOverride ?? workspaceLocale;
  const tx = useCallback(
    (text: string, params?: PitchTranslationParams) => pitchTranslate(locale, text, params),
    [locale]
  );
  const txAddLabel = useCallback((label: string) => {
    const action = pitchTranslate(locale, "Add");
    return locale === "zh-TW" ? `${action}${label}` : `${action} ${label}`;
  }, [locale]);
  const txMaximumItems = useCallback((count: number, item: "Columns" | "Rows") => {
    const translatedItem = pitchTranslate(locale, item);
    return locale === "zh-TW" ? `最多 ${count} ${translatedItem}` : `Maximum ${count} ${translatedItem.toLowerCase()}`;
  }, [locale]);
  return { locale, tx, txAddLabel, txMaximumItems };
}
